SQLITE_SCHEMA = TABLES + """
CREATE TRIGGER IF NOT EXISTS audit_no_update BEFORE UPDATE ON audit_log
BEGIN SELECT RAISE(ABORT, 'audit_log is append-only'); END;
CREATE TRIGGER IF NOT EXISTS audit_no_delete BEFORE DELETE ON audit_log
BEGIN SELECT RAISE(ABORT, 'audit_log is append-only'); END;
"""

POSTGRES_TRIGGERS = """
CREATE OR REPLACE FUNCTION audit_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'audit_log is append-only'; END $$;
CREATE OR REPLACE TRIGGER audit_no_update BEFORE UPDATE ON audit_log
    FOR EACH ROW EXECUTE FUNCTION audit_append_only();
CREATE OR REPLACE TRIGGER audit_no_delete BEFORE DELETE ON audit_log
    FOR EACH ROW EXECUTE FUNCTION audit_append_only();
CREATE OR REPLACE TRIGGER audit_no_truncate BEFORE TRUNCATE ON audit_log
    FOR EACH STATEMENT EXECUTE FUNCTION audit_append_only();
"""


def _postgres_schema() -> str:
    ddl = TABLES.replace("INTEGER PRIMARY KEY", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    ddl = ddl.replace("(datetime('now'))", "(to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'))")
    ddl = re.sub(r"REAL", "DOUBLE PRECISION", ddl).replace("BLOB", "BYTEA")
    return ddl + POSTGRES_TRIGGERS


# Serializes writers. On Postgres an advisory lock extends this across instances, so the audit
# hash chain stays linear even with several app replicas.
_write_lock = threading.Lock()
_AUDIT_LOCK_KEY = 0x5E1A5
_db_path: Path | None = None
_pool: Any = None


class Row(tuple):
    """Postgres row that behaves like sqlite3.Row: index or column-name access, and dict(row)."""

    _index: dict[str, int]

    def __getitem__(self, key):
        return tuple.__getitem__(self, self._index[key] if isinstance(key, str) else key)

    def keys(self) -> list[str]:
        return list(self._index)


def _row_factory(cursor):
    index = {c.name: i for i, c in enumerate(cursor.description or ())}

    def make(values):
        row = Row(values)
        row._index = index
        return row

    return make


@lru_cache(maxsize=512)
def _pg_sql(sql: str) -> str:
    return sql.replace("%", "%%").replace("?", "%s")


class Conn:
    """Thin adapter over a sqlite3 or psycopg connection."""

    def __init__(self, raw, postgres: bool):
        self.raw, self.postgres = raw, postgres

    def execute(self, sql: str, params: tuple | list = ()):
        return self.raw.execute(_pg_sql(sql) if self.postgres else sql, params)

    def executemany(self, sql: str, rows: list) -> None:
        if self.postgres:
            with self.raw.cursor() as cur:
                cur.executemany(_pg_sql(sql), rows)
        else:
            self.raw.executemany(sql, rows)

    def insert(self, sql: str, params: tuple | list = ()) -> int:
        """INSERT and return the new row's id."""
        if self.postgres:
            return self.raw.execute(_pg_sql(sql) + " RETURNING id", params).fetchone()[0]
        return self.raw.execute(sql, params).lastrowid

    def apply_schema(self) -> None:
        if self.postgres:
            self.raw.execute(_postgres_schema())
        else:
            self.raw.executescript(SQLITE_SCHEMA)
            # Additive migrations for databases created before a column existed.
            have = {r["name"] for r in self.raw.execute("PRAGMA table_info(queries)")}
            for column in ("refusal_reason", "trace"):
                if column not in have:
                    self.raw.execute(f"ALTER TABLE queries ADD COLUMN {column} TEXT")


def is_postgres() -> bool:
    return _pool is not None


def init(target: str | Path) -> None:
    """`target` is a postgres:// URL or a SQLite file path."""
    global _db_path, _pool
    close()
    if str(target).startswith(("postgres://", "postgresql://")):
        from psycopg.types.numeric import FloatLoader
        from psycopg_pool import ConnectionPool

        def configure(conn) -> None:
            conn.adapters.register_loader("numeric", FloatLoader)  # SUM/AVG -> float, not Decimal

        _pool = ConnectionPool(str(target), min_size=1, max_size=10, configure=configure,
                               kwargs={"row_factory": _row_factory}, check=ConnectionPool.check_connection,
                               open=True)
        atexit.register(close)
        with write() as conn:  # the advisory lock also stops replicas racing on first-boot DDL
            conn.apply_schema()
    else:
        path = Path(target)
        path.parent.mkdir(parents=True, exist_ok=True)
        _db_path = path
        with connect() as conn:
            conn.apply_schema()


def close() -> None:
    global _pool
    if _pool is not None:
        _pool.close()
        _pool = None


def _open_sqlite() -> sqlite3.Connection:
    assert _db_path is not None, "db.init() was not called"
    conn = sqlite3.connect(_db_path, timeout=30, check_same_thread=False)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA journal_mode=WAL")
    conn.execute("PRAGMA foreign_keys=ON")
    return conn


@contextmanager
def connect() -> Iterator[Conn]:
    if _pool is not None:
        with _pool.connection() as raw:  # commits on success, rolls back on error
            yield Conn(raw, True)
        return
    raw = _open_sqlite()
    try:
        yield Conn(raw, False)
        raw.commit()
    except Exception:
        raw.rollback()
        raise
    finally:
        raw.close()


@contextmanager
def write() -> Iterator[Conn]:
    """Serialized writer: keeps the audit hash chain consistent under concurrency."""
    with _write_lock, connect() as conn:
        if conn.postgres:
            conn.execute("SELECT pg_advisory_xact_lock(?)", (_AUDIT_LOCK_KEY,))
        yield conn


def _stamp(t: datetime) -> str:
    return t.strftime("%Y-%m-%d %H:%M:%S")  # same text format as the created_at column defaults


def days_ago(days: int) -> str:
    return _stamp(datetime.now(timezone.utc) - timedelta(days=days))


def month_start() -> str:
    return _stamp(datetime.now(timezone.utc).replace(day=1, hour=0, minute=0, second=0, microsecond=0))
